def names(block: str) -> frozenset[str]:
    return frozenset(block.split())


GIVEN_NAMES = names(UKRAINIAN_GIVEN) | names(RUSSIAN_GIVEN) | names(WESTERN_GIVEN)


def is_cyrillic(text: str) -> bool:
    return bool(CYRILLIC.match(text))


def is_given(token: str) -> bool:
    return token.rstrip(".").lower() in GIVEN_NAMES


def is_initial(token: str) -> bool:
    return len(token.rstrip(".")) == 1


def is_patronymic(token: str) -> bool:
    return "-" not in token and bool(PATRONYMIC.search(token)) and not is_given(token)


def has_surname_suffix(token: str) -> bool:
    return bool(SURNAME_SUFFIX.search(token)) and not is_given(token)


def given_first(tokens: list[str]) -> bool:
    first, last = tokens[0], tokens[-1]
    if len(tokens) == 3 and is_patronymic(tokens[1]):
        return True
    if is_patronymic(last):
        return False
    if is_given(first) or is_initial(first):
        return not is_given(last) or is_initial(last) or has_surname_suffix(last)
    if is_given(last) or is_initial(last):
        return False
    if has_surname_suffix(last) != has_surname_suffix(first):
        return has_surname_suffix(last)
    return True


def surname_first(tokens: list[str]) -> str:
    if given_first(tokens):
        *given, surname = tokens
        return f"{surname}, {' '.join(given)}"
    surname, *given = tokens
    return f"{surname}, {' '.join(given)}"
